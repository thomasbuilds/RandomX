rows.append(["v1 as specified (256 instr, k=1)", f(ratio_with(p["Tprog1"], 1), 2)])
rows.append(["v2 as specified (384 instr, k=2)", f(ratio_with(p["Tprog1"] * p["v2scale"], 2), 2)])
