rows.append(["v2 with 256 instructions (k=2)", f(ratio_with(p["Tprog1"], 2), 2)])
rows.append(["v2 with fewer iterations (any count, k=2): unchanged", f(ratio_with(p["Tprog1"] * p["v2scale"], 2), 2)])
