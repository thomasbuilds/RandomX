def e_iter(v, i):
    c = VM[v]
    e = (c["alu"] * E["alu"][i] + c["mul"] * E["mul"][i] + c["fpadd"] * E["fpadd"][i] + c["fpmul"] * E["fpmul"][i] +
         c["fpdiv"] * E["fpdiv"][i] + c["fpsqrt"] * E["fpsqrt"][i] + (c["rdL1"] + c["stL1"]) * E["l1"][i] +
         (c["rdL2"] + c["stL2"]) * E["l2"][i] + (c["rdL3"] + c["stL3"]) * E["l3_8"][i] + 4 * E["l3_64"][i] +
         (c["instr"] + c["cbr_reexec"]) * E["instr"][i] + c["aes"] * E["aes"][i])
    return e  # pJ per iteration (without the Dataset read)


def e_item(i):
    return SSH_MUL_ITEM * E["mul"][i] + SSH_ALU_ITEM * E["alu"][i] + SSH_INSTR_ITEM * E["ssh_op"][i] + 8 * E["cache64"][i]


